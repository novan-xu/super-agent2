describe("the list", () => {
  it("covers every form in the design", () => {
    expect(irreversibleForms.map((form) => form.id)).toEqual([
      "repository-deletion",
      "repository-publication",
      "default-branch-rewrite",
      "data-deletion",
      "credential-change",
      "file-deletion",
    ]);
  });
});

describe("commands that cannot be undone", () => {
  it.each(held.map(([command, form, cwd]) => ({ command, form, cwd })))("holds $command as $form", ({ command, form, cwd }) => {
    const match = findIrreversible({ command, cwd: at(cwd) }, settings);
    expect(match?.form).toBe(form);
  });
});

describe("ordinary commands", () => {
  it.each(ordinary.map(([command, cwd]) => ({ command, cwd })))("lets $command run", ({ command, cwd }) => {
    expect(findIrreversible({ command, cwd: at(cwd) }, settings)).toBeUndefined();
  });
});

describe("evidence", () => {
  it("says what was matched", () => {
    const match = findIrreversible({ command: "cd /srv/projects/app && gh repo delete novan-xu/x --yes", cwd: null }, settings);
    expect(match).toEqual({ form: "repository-deletion", description: text("hold.form.repositoryDeletion"), evidence: "gh repo delete novan-xu/x --yes" });
    const deletion = findIrreversible({ command: "rm -rf /data/old", cwd: project }, settings);
    expect(deletion?.evidence).toContain("/data/old");
  });
});

describe("project folders and credential paths", () => {
  it("come from configuration", () => {
    const empty = lockSettings({ projectFolders: [], credentialPaths: [] });
    expect(findIrreversible({ command: "rm -rf node_modules", cwd: project }, empty)?.form).toBe("file-deletion");
    expect(findIrreversible({ command: "rm -rf node_modules", cwd: project }, settings)).toBeUndefined();
    expect(findIrreversible({ command: "echo x > /srv/vault/token", cwd: project }, empty)).toBeUndefined();
    expect(findIrreversible({ command: "echo x > /srv/vault/token", cwd: project }, settings)?.form).toBe("credential-change");
  });

  it("compare Linux paths by case and Windows paths without it", () => {
    expect(findIrreversible({ command: "rm -rf /SRV/projects/app/dist", cwd: project }, settings)?.form).toBe("file-deletion");
    expect(findIrreversible({ command: "Remove-Item -Recurse c:\\WORK\\app\\dist", cwd: windowsProject }, settings)).toBeUndefined();
  });
});
