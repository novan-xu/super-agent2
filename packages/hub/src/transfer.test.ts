import { existsSync, mkdtempSync, readFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { WebSocket } from "ws";
import { afterEach, beforeEach, describe, expect, it } from "vitest";
import type { Hub } from "./hub.js";
import { assertion, keySet, signingKey, type SigningKey, staticKeySource, TestClock, testConfig } from "./testing/access.js";
import { testCredentials } from "./testing/commands.js";
import { startTestHub } from "./testing/http.js";

let dir: string;
let clock: TestClock;
let key: SigningKey;
let hub: Hub | undefined;
beforeEach(async () => { dir = mkdtempSync(join(tmpdir(), "transfer-")); clock = new TestClock(); key = await signingKey("key"); });
afterEach(async () => { await hub?.close(); hub = undefined; rmSync(dir, { recursive: true, force: true }); });

describe("device transfer", () => {
  it("stores exact text and uploaded files independently, broadcasts changes, pages and deletes", async () => {
    hub = await startTestHub({ config: testConfig(dir), keySource: staticKeySource(keySet(key)), clock, credentials: testCredentials });
    const base = `http://127.0.0.1:${hub.address.port}`;
    const token = await assertion({ key, clock });
    const request = (path: string, init: RequestInit = {}) => fetch(base + path, { ...init, headers: { "Cf-Access-Jwt-Assertion": token, origin: base, ...init.headers } });
    const json = (path: string, body: unknown) => request(path, { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify(body) });
    const ws = new WebSocket(base.replace("http", "ws") + "/ws", { headers: { "Cf-Access-Jwt-Assertion": token, origin: base } });
    await new Promise<void>((resolve, reject) => { ws.once("open", resolve); ws.once("error", reject); });
    const changed = () => new Promise<void>((resolve) => { const onMessage = (data: Buffer) => { if (JSON.parse(data.toString()).type === "transfer.changed") { ws.off("message", onMessage); resolve(); } }; ws.on("message", onMessage); });
    const created = await json("/api/transfer/files", { name: "test.txt", size: 4, mediaType: "text/plain" });
    const { attachment } = await created.json() as { attachment: { id: string } };
    expect((await json("/api/transfer", { text: "", device: "phone", files: [attachment.id] })).status).toBe(409);
    expect((await request(`/api/transfer/files/${attachment.id}/upload?offset=0`, { method: "PUT", headers: { "content-type": "application/octet-stream" }, body: "data" })).status).toBe(200);
    expect(await (await request(`/api/transfer/files/${attachment.id}`)).text()).toBe("data");
    expect((await request(`/api/attachments/${attachment.id}`)).status).toBe(404);
    expect(hub.attachments.get(attachment.id)).toBeUndefined();
    const file = join(dir, "transfer", attachment.id, "test.txt");
    expect(readFileSync(file, "utf8")).toBe("data");
    const notification = changed();
    expect((await json("/api/transfer", { text: "  hi\nhttps://example.com  ", device: "phone", files: [attachment.id] })).status).toBe(201);
    await notification;
    expect((await request(`/api/transfer/files/${attachment.id}/upload?offset=0`, { method: "PUT", headers: { "content-type": "application/octet-stream" }, body: "evil" })).status).toBe(409);
    const conversation = hub.conversations.create();
    expect((await json(`/api/conversations/${conversation.id}/messages`, { text: "test", attachments: [attachment.id] })).status).toBe(409);
    const page = await (await request("/api/transfer")).json() as { items: { seq: number; text: string; files: unknown[] }[]; more: boolean };
    expect(page.items).toMatchObject([{ text: "  hi\nhttps://example.com  ", files: [{ id: attachment.id }] }]);
    expect(page.more).toBe(false);
    expect((await (await request(`/api/transfer?before=${page.items[0]?.seq}`)).json() as { items: unknown[] }).items).toEqual([]);
    expect(hub.database.connection.prepare("SELECT count(*) AS n FROM conversation_entries").get()).toMatchObject({ n: 0 });
    const deletion = changed();
    expect((await request(`/api/transfer/${page.items[0]?.seq}`, { method: "DELETE" })).status).toBe(200);
    await deletion;
    expect(existsSync(file)).toBe(false);
    expect((await request(`/api/transfer/files/${attachment.id}`)).status).toBe(404);
    ws.close();
  });
  it("renders transfer HTML using the same isolation as attachments", async () => {
    hub = await startTestHub({ config: testConfig(dir), keySource: staticKeySource(keySet(key)), clock, credentials: testCredentials });
    const base = `http://127.0.0.1:${hub.address.port}`;
    const token = await assertion({ key, clock });
    const request = (path: string, init: RequestInit = {}) => fetch(base + path, { ...init, headers: { "Cf-Access-Jwt-Assertion": token, origin: base, ...init.headers } });
    const html = "<style>body { color: red }</style>";
    const created = await request("/api/transfer/files", { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ name: "page.htm", size: html.length, mediaType: "text/html" }) });
    const { attachment } = await created.json() as { attachment: { id: string } };
    await request(`/api/transfer/files/${attachment.id}/upload?offset=0`, { method: "PUT", headers: { "content-type": "application/octet-stream" }, body: html });
    const response = await request(`/api/transfer/files/${attachment.id}/render`);
    expect(response.status).toBe(200);
    expect(response.headers.get("content-security-policy")).toContain("style-src 'unsafe-inline'");
    expect(await response.text()).toBe(html);
  });
  it("enforces upload and origin boundaries", async () => {
    hub = await startTestHub({ config: testConfig(dir), keySource: staticKeySource(keySet(key)), clock, credentials: testCredentials });
    const base = `http://127.0.0.1:${hub.address.port}`;
    const token = await assertion({ key, clock });
    const send = (path: string, body: unknown, origin = base) => fetch(base + path, { method: "POST", headers: { "Cf-Access-Jwt-Assertion": token, origin, "content-type": "application/json" }, body: JSON.stringify(body) });
    expect((await send("/api/transfer/files", { name: "huge", size: 100 * 1024 * 1024 + 1, mediaType: "" })).status).toBe(400);
    expect((await send("/api/transfer", { text: "x", device: "desktop", files: [] }, "https://other.example")).status).toBe(403);
    expect((await send("/api/transfer", { text: "", device: "desktop", files: [] })).status).toBe(400);
    for (let i = 0; i < 52; i++) expect((await send("/api/transfer", { text: String(i), device: "desktop", files: [] })).status).toBe(201);
    const page = await (await fetch(base + "/api/transfer", { headers: { "Cf-Access-Jwt-Assertion": token } })).json() as { items: { seq: number; text: string }[]; more: boolean };
    expect(page.more).toBe(true);
    expect(page.items.map((item) => item.text)).toEqual(Array.from({ length: 50 }, (_, i) => String(i + 2)));
    const older = await (await fetch(base + `/api/transfer?before=${page.items[0]?.seq}`, { headers: { "Cf-Access-Jwt-Assertion": token } })).json() as { items: { text: string }[]; more: boolean };
    expect(older.items.map((item) => item.text)).toEqual(["0", "1"]);
    expect(older.more).toBe(false);
  });
});
